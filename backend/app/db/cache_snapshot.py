"""Extraction-cache snapshot for the sample PDFs (PRD §12.7, DEC-014).

backend/seed/extraction_cache.json is a CACHE SNAPSHOT, not fixture data: it is regenerated
from real extractions by `python -m app.tools.warm_cache`, never hand-edited, and loaded only
when extraction_cache is empty, so the rehearsed demo survives a redeploy on an ephemeral disk.
Runs that use it still show the "Cached extraction" badge.
"""
import hashlib
import json
import sqlite3
from pathlib import Path

from app.services.extraction.schema import InvoiceExtraction
from app.utils.timeutil import now_iso

SNAPSHOT_VERSION = 1


def export_snapshot(conn: sqlite3.Connection, path: Path, samples_dir: Path) -> int:
    """Write the cache rows whose file_hash belongs to a sample PDF. Returns the row count."""
    by_hash = {hashlib.sha256(p.read_bytes()).hexdigest(): p.name for p in sorted(samples_dir.glob("*.pdf"))}
    rows = conn.execute(
        "SELECT file_hash, provider, model, ingest_method, payload, extracted_at FROM extraction_cache"
    ).fetchall()
    records = sorted(
        ({"file_name": by_hash[r["file_hash"]], "file_hash": r["file_hash"], "provider": r["provider"],
          "model": r["model"], "ingest_method": r["ingest_method"], "extracted_at": r["extracted_at"],
          "payload": json.loads(r["payload"])} for r in rows if r["file_hash"] in by_hash),
        key=lambda x: x["file_name"])
    doc = {
        "_meta": {
            "snapshot_version": SNAPSHOT_VERSION,
            "kind": "extraction cache snapshot (DEC-014) - regenerated by python -m app.tools.warm_cache; never hand-edit",
            "exported_at": now_iso(),
        },
        "records": records,
    }
    path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return len(records)


def load_snapshot_if_empty(conn: sqlite3.Connection, path: Path | None) -> int:
    """Load the snapshot into an EMPTY extraction_cache. Returns rows loaded (0 if skipped)."""
    if path is None or not path.exists():
        return 0
    if conn.execute("SELECT EXISTS (SELECT 1 FROM extraction_cache)").fetchone()[0]:
        return 0
    doc = json.loads(path.read_text(encoding="utf-8"))
    conn.execute("BEGIN IMMEDIATE")
    try:
        for r in doc["records"]:
            payload = InvoiceExtraction.model_validate(r["payload"])     # reject a corrupted snapshot
            conn.execute(
                "INSERT INTO extraction_cache (file_hash, provider, model, ingest_method, payload, extracted_at) "
                "VALUES (?, ?, ?, ?, ?, ?)",
                (r["file_hash"], r["provider"], r["model"], r["ingest_method"], payload.model_dump_json(),
                 r["extracted_at"]),
            )
        conn.execute("COMMIT")
    except Exception:
        conn.execute("ROLLBACK")
        raise
    return len(doc["records"])
